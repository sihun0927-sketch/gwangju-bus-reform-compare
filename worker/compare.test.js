test("지표 표는 다섯 줄이고 정류장 수만 경로 줄에 남는다", async () => {
  // 지표는 두 카드를 같은 줄끼리 견주는 자리다(CONTEXT 「지표」). 노선번호·배차간격은 구간마다
  // 달라지므로 경로가 쓰는 값을 차례대로 「·」로 잇는다. 정류장 수는 경로 줄에만 있다
  const 글 = await 비교(전남대, 광주송정역);
  const 개편_후 = 카드(글, "after");
  assert.equal(지표(개편_후, "예상 시간"), "7분");
  assert.equal(지표(개편_후, "환승"), "없음");
  assert.equal(지표(개편_후, "도보 합계"), "20m");
  assert.ok(지표(개편_후, "노선번호"), "노선번호도 지표 표에 선다");
  assert.match(지표(개편_후, "배차간격"), /^약 [\d.]+분\(추정\)$/, "개편 후는 추정값이고 그렇다고 적힌다");
  assert.equal(지표(개편_후, "정류장 수"), undefined, "정류장 수는 경로 줄에만 있다");
  assert.match(개편_후, /배차간격 약 [\d.]+분\(추정\) · \d+개 정류장/, "경로 줄의 노선별 값");

  const 정류장_합 = [...개편_후.matchAll(/· (\d+)개 정류장</g)]
    .reduce((합, m) => 합 + Number(m[1]), 0);
  assert.equal(정류장_합, 21, "구간별 정류장 수를 더하면 경로 전체가 지나는 수다");

  // 추정치 문구는 카드 **밖** 각주 한 벌에만 있다 (CONTEXT 「개편 전 카드 / 개편 후 카드」)
  assert.ok(!개편_후.includes("추정치"), "카드 안에는 없다");
  assert.equal(글.match(/추정치/g).length, 1, "카드 둘이 나눠 쓰는 각주라 조각에 한 번뿐이다");
  assert.match(글, /<ul class="notes">[^]*추정치/);
});

test("배차간격은 개편 전이 공표값, 개편 후가 추정값이고 화면이 그것을 가른다", async () => {
  // 같은 칸에 나란히 서는 값이 출처가 다르다(CONTEXT 「경로 줄」·ADR-0010). 안 가르면 시민이
  // 추정을 공표값으로 읽는다. 「분」은 조각이 붙이고 번들에는 숫자만 있다.
  // 환승 2회 쌍을 쓴다 — 구간마다 값이 따로 붙는 것과, 지표 표가 그 값을 차례대로 잇는 것을 함께 본다
  const 글 = await 비교(승촌주택단지, 앵남2구);
  const 개편_전 = 카드(글, "before");
  assert.match(개편_전, /배차간격 30분 · \d+개 정류장/, 개편_전);
  assert.match(개편_전, /배차간격 50분 · \d+개 정류장/, "구간마다 그 노선의 값이다");
  assert.ok(!개편_전.includes("배차간격 정보 없음"), "개편 전 세 노선 모두 값이 있다");
  assert.ok(!개편_전.includes("(추정)"), "공표값에는 「추정」을 안 붙인다");

  const 개편_후 = 카드(글, "after");
  assert.match(개편_후, /배차간격 약 [\d.]+분\(추정\)/, "개편 후는 추정값이라고 적는다");
  assert.ok(!개편_후.includes("배차간격 정보 없음"), "개편 후 노선 118개는 모두 추정값이 있다");

  // 환승 경로의 지표 표 — 구간 셋의 값이 차례대로 한 칸에 선다(CONTEXT 「지표」)
  assert.equal(지표(개편_전, "배차간격"), "30분 · 30분 · 50분", "구간 차례 그대로 잇는다");
  assert.equal(지표(개편_전, "노선번호"), "대촌70 · 봉선76 · 진월177", "노선번호도 같은 차례다");

  // 순환01은 시 배차 파일이 「순환01A(…)」「순환01B(…)」 둘로 갈라 적은 유일한 노선이다.
  // 이름이 그대로 안 맞아 여태 화면에 「정보 없음」으로 떴다(2026-09-04에 고침) — A·B 평균 10분
  const 순환 = 카드(await 비교(시청, 교육대), "before");
  assert.ok(순환.includes("순환01"), 순환);
  assert.match(순환, /배차간격 10분/, "A·B로 갈라 적힌 노선도 값을 찾는다");
  assert.ok(!순환.includes("배차간격 정보 없음"), "이제 개편 전에 빈칸은 없다");
});

